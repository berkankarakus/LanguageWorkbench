using Intermediate.Code;
using Intermediate.Symbols;
using Messaging;

namespace Backend;

/// <summary>
/// The framework class that represents the back-end component.
/// </summary>
public abstract class BackendProcessor : IMessageProducer
{
    // MessageHandler delegate
    private static readonly MessageHandler MessageHandler;
    protected ISymbolTable? SymbolTable { get; set; }
    protected ICode? Code { get; set; }

    static BackendProcessor()
    {
        MessageHandler = new MessageHandler();
    }

    /// <summary>
    /// Process the intermediate code and the symbol table generated by the parser.
    /// </summary>
    /// <remarks>
    /// To be implemented by a compiler or an interpreter subclass.
    /// </remarks>
    /// <param name="iCode">The intermediate code to process.</param>
    /// <param name="symbolTable">The symbol table produced by the front end.</param>
    public abstract void Process(ICode iCode, ISymbolTable symbolTable);

    public void AddMessageListener(IMessageListener listener)
    {
        MessageHandler.AddListener(listener);
    }

    public void RemoveMessageListener(IMessageListener listener)
    {
        MessageHandler.RemoveListener(listener);
    }

    public void SendMessage(Message message)
    {
        MessageHandler.SendMessage(message);
    }
}
