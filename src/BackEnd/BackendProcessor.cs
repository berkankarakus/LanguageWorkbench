using Intermediate.Code.Interfaces;
using Intermediate.Symbols.Interfaces;
using Messaging;

namespace Backend;

/// <summary>
/// The framework class that represents the back-end component.
/// </summary>
public abstract class BackendProcessor : IMessageProducer
{
    private readonly MessageHandler _messageHandler;
    /// <summary>
    /// Initializes a root backend processor with an isolated message publisher.
    /// </summary>
    protected BackendProcessor()
    {
        _messageHandler = new();
    }

    /// <summary>
    /// Initializes a child backend processor that shares its parent's message publisher.
    /// </summary>
    /// <param name="parent">The parent backend processor.</param>
    protected BackendProcessor(BackendProcessor parent)
    {
        ArgumentNullException.ThrowIfNull(parent);

        _messageHandler = parent._messageHandler;
    }

    /// <summary>
    /// Processes the intermediate code and symbol-table stack generated by the parser.
    /// </summary>
    /// <remarks>
    /// To be implemented by a compiler or an interpreter subclass.
    /// </remarks>
    /// <param name="intermediateCode">The intermediate code to process.</param>
    /// <param name="symbolTableStack">The symbol-table stack produced by the front end.</param>
    public abstract void Process(IIntermediateCode intermediateCode, ISymbolTableStack symbolTableStack);

    public void AddMessageListener(IMessageListener listener)
    {
        _messageHandler.AddListener(listener);
    }

    public void RemoveMessageListener(IMessageListener listener)
    {
        _messageHandler.RemoveListener(listener);
    }

    public void SendMessage(Message message)
    {
        _messageHandler.SendMessage(message);
    }
}
