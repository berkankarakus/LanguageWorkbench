using FrontEnd.Scanning;
using FrontEnd.Tokens;
using Intermediate.Code;
using Intermediate.Symbols;
using Messaging;

namespace FrontEnd.Parsing;

/// <summary>
/// Provides a language-independent base for parsers.
/// Language-specific parsers derive from this class.
/// </summary>
public abstract class Parser(Scanner scanner) : IMessageProducer
{
    protected static ISymbolTable? SymbolTable { get; } = null; // Generated symbol table.
    private static readonly MessageHandler MessageHandler = new();

    protected ICode? Code { get; set; } // Intermediate code generated by this parser.

    /// <summary>
    /// Parses a source program and generates the intermediate code and the symbol table.
    /// To be implemented by a language-specific parser subclass.
    /// </summary>
    /// <exception cref="Exception">
    /// Thrown if an error occurs during parsing.
    /// </exception>
    public abstract void Parse();

    /// <summary>
    /// Returns the number of syntax errors found by the parser.
    /// To be implemented by a language-specific parser subclass.
    /// </summary>
    /// <returns>The number of syntax errors found.</returns>
    /// <exception cref="Exception">
    /// Thrown if an error occurs while determining the error count.
    /// </exception>
    public abstract int GetErrorCount();

    /// <summary>
    /// Calls the scanner's <see cref="Scanner.CurrentToken"/> method.
    /// </summary>
    /// <returns>The current token.</returns>
    public Token? CurrentToken()
    {
        return scanner.CurrentToken();
    }

    /// <summary>
    /// Calls the scanner's <see cref="Scanner.NextToken"/> method.
    /// </summary>
    /// <returns>The next token.</returns>
    /// <exception cref="Exception">
    /// Thrown if an error occurs while retrieving the next token.
    /// </exception>
    public Token NextToken()
    {
        return scanner.NextToken();
    }

    /// <summary>
    /// Add a parser message listener.
    /// </summary>
    /// <param name="listener"></param>
    public void AddMessageListener(IMessageListener listener)
    {
        MessageHandler.AddListener(listener);
    }

    /// <summary>
    /// Remove a parser message listener.
    /// </summary>
    /// <param name="listener"></param>
    public void RemoveMessageListener(IMessageListener listener)
    {
        MessageHandler.RemoveListener(listener);
    }

    /// <summary>
    /// Notify listeners after setting the message.
    /// </summary>
    /// <param name="message"></param>
    /// <exception cref="NotImplementedException"></exception>
    public void SendMessage(Message message)
    {
        MessageHandler.SendMessage(message);
    }
}
